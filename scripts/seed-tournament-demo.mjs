// Demo MLBB tournament for trying the module end to end: 8 approved teams ×
// 5 players, a full round robin with results, one live match and the rest
// upcoming.
//
//   node scripts/seed-tournament-demo.mjs            # dry run (prints the plan)
//   node scripts/seed-tournament-demo.mjs --apply    # write it
//   node scripts/seed-tournament-demo.mjs --remove   # delete the demo again
//
// Writes to whatever .env.local points at, so it stays out of sight there:
// the tournament is created UNPUBLISHED (only admins can open it, via
// "Buka app peserta"), under the slug `demo-mlbb`. No customers, vouchers or
// WhatsApp messages are created — the players' phones are placeholders.
//
// Needs migration 20260929_tournament.sql.

import fs from "fs";
import { randomUUID } from "crypto";

const APPLY = process.argv.includes("--apply");
const REMOVE = process.argv.includes("--remove");
const SLUG = "demo-mlbb";

const env = Object.fromEntries(
  fs.readFileSync(".env.local", "utf8").split("\n")
    .filter(l => l.includes("=") && !l.trim().startsWith("#"))
    .map(l => { const i = l.indexOf("="); return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^["']|["']$/g, "")]; })
);
const U = env.NEXT_PUBLIC_SUPABASE_URL, K = env.SUPABASE_SERVICE_ROLE_KEY;
if (!U || !K) { console.error("Missing Supabase env"); process.exit(1); }
const H = { apikey: K, Authorization: "Bearer " + K, "Content-Type": "application/json", Prefer: "return=representation" };

async function rest(method, path, body) {
  const r = await fetch(`${U}/rest/v1/${path}`, { method, headers: H, body: body ? JSON.stringify(body) : undefined });
  const text = await r.text();
  if (!r.ok) throw new Error(`${method} ${path}: ${r.status} ${text.slice(0, 200)}`);
  return text ? JSON.parse(text) : null;
}

const existing = await rest("GET", `tournaments?select=id&slug=eq.${SLUG}`);

if (REMOVE) {
  if (!existing.length) { console.log("No demo tournament to remove."); process.exit(0); }
  await rest("DELETE", `tournaments?slug=eq.${SLUG}`);
  console.log("Removed demo tournament (teams, players, matches cascade).");
  process.exit(0);
}
if (existing.length) {
  console.log(`A tournament with slug "${SLUG}" already exists. Run with --remove first.`);
  process.exit(0);
}

const TEAMS = [
  ["Team Syabab", "SYB"], ["Alpha Squad", "ALP"], ["Bravo Esports", "BRV"], ["Kopi Gaming", "KOP"],
  ["Loka Legends", "LKL"], ["Night Owls", "OWL"], ["Red Maroon", "RED"], ["Espresso Five", "ESP"],
];
const ROLES = ["exp", "jungler", "mid", "gold", "roamer"];

// Circle-method round robin (same as lib/tournament/schedule.ts).
function rounds(ids) {
  const list = [...ids];
  const out = [];
  for (let r = 0; r < list.length - 1; r++) {
    const pairs = [];
    for (let i = 0; i < list.length / 2; i++) {
      const a = list[i], b = list[list.length - 1 - i];
      pairs.push(r % 2 ? [b, a] : [a, b]);
    }
    out.push(pairs);
    list.splice(1, 0, list.pop());
  }
  return out;
}

const tId = randomUUID();
const now = Date.now();
const start = new Date(now - 3 * 60 * 60 * 1000); // started 3h ago
start.setMinutes(0, 0, 0);

const tournament = {
  id: tId, slug: SLUG, name: "Loka MLBB Cup (Demo)", venue: "Loka Cafe",
  description: "Demo tournament — generated by scripts/seed-tournament-demo.mjs.\nWin = 3 pts. BO1 group stage.",
  format: "round_robin", status: "ongoing", published: false,
  start_at: start.toISOString(), end_at: new Date(start.getTime() + 10 * 3600e3).toISOString(),
  max_teams: 8, min_players: 5, max_players: 6, entry_fee: 50,
  payment_instructions: "Maybank 0000 0000 0000\nLoka Cafe (demo)",
  default_best_of: 1, knockout_best_of: 3, points_win: 3, points_loss: 0,
  voucher_config: {
    discount: { enabled: true, type: "amount", value: 5, min_spend: 10, validity_days: 30 },
    event_day: { enabled: true, type: "percent", value: 10, max_discount: 10 },
  },
};

const teams = TEAMS.map(([name, short], i) => ({
  id: randomUUID(), tournament_id: tId, name, short_name: short, team_number: i + 1,
  registration_status: "approved", contact_phone: `010000${String(i + 1).padStart(2, "0")}01`,
  notes: "Demo team",
}));

const players = teams.flatMap((t, ti) => ROLES.map((role, pi) => ({
  tournament_id: tId, team_id: t.id,
  full_name: `${t.short_name} Player ${pi + 1}`, ign: `${t.short_name}.${["Zeke", "Kai", "Nova", "Vex", "Rui"][pi]}`,
  mlbb_user_id: String(100000000 + ti * 10 + pi), server_id: String(2000 + ti),
  phone: `010000${String(ti + 1).padStart(2, "0")}${String(pi + 1).padStart(2, "0")}`,
  player_role: role, is_captain: pi === 0,
})));

// 28 BO1 matches on 2 stations, 30 min apart. First 12 done, #13 live, rest upcoming.
const matches = [];
let n = 1;
rounds(teams.map(t => t.id)).forEach((pairs, r) => {
  for (const [a, b] of pairs) {
    const idx = n - 1;
    const m = {
      tournament_id: tId, match_number: n, stage: "group", round_index: r + 1, round_name: `Round ${r + 1}`,
      team_a_id: a, team_b_id: b, best_of: 1,
      scheduled_at: new Date(start.getTime() + Math.floor(idx / 2) * 30 * 60e3).toISOString(),
      station: `Station ${(idx % 2) + 1}`, status: "scheduled", team_a_score: 0, team_b_score: 0, winner_team_id: null, lobby_info: null,
    };
    if (n <= 12) {
      const aWins = (n * 7 + r) % 3 !== 0;
      Object.assign(m, { status: "completed", team_a_score: aWins ? 1 : 0, team_b_score: aWins ? 0 : 1, winner_team_id: aWins ? a : b });
    } else if (n === 13) {
      Object.assign(m, { status: "live", lobby_info: "Room 482193 · pass loka" });
    }
    matches.push(m);
    n++;
  }
});

const announcements = [
  { tournament_id: tId, title: "Welcome to Loka MLBB Cup!", message: "Check in at the counter 15 minutes before your match.", priority: "normal" },
  { tournament_id: tId, title: "Station 2 delayed 10 min", message: "Device issue — sorry!", priority: "urgent" },
];

console.log(`Plan: 1 tournament (unpublished, slug ${SLUG}), ${teams.length} teams, ${players.length} players, ${matches.length} matches (${matches.filter(m => m.status === "completed").length} completed, 1 live), ${announcements.length} announcements.`);
console.log(`Target: ${U}`);
if (!APPLY) { console.log("Dry run — pass --apply to write."); process.exit(0); }

await rest("POST", "tournaments", tournament);
await rest("POST", "tournament_teams", teams);
await rest("POST", "tournament_players", players);
await rest("POST", "tournament_matches", matches);
await rest("POST", "tournament_announcements", announcements);
console.log(`Done. Admin: /dashboard/tournaments/${tId}   Preview (admin only): /tournament/${SLUG}`);
